def set_cell(cell, text: str, bold: bool = False, header_cell: bool = False) -> None:
    cell.text = ""
    paragraph = cell.paragraphs[0]
    run = paragraph.add_run(text)
    run.bold = bold
    run.font.size = Pt(9)
    cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
    if header_cell:
        tc_pr = cell._tc.get_or_add_tcPr()
        shading = OxmlElement("w:shd")
        shading.set(qn("w:fill"), "D9EAF7")
        tc_pr.append(shading)


def parse_table(lines: list[str], start: int) -> tuple[list[list[str]], int]:
    rows: list[list[str]] = []
    index = start
    while index < len(lines) and lines[index].strip().startswith("|"):
        line = lines[index].strip()
        cells = [cell.strip() for cell in line.strip("|").split("|")]
        if not all(re.fullmatch(r":?-+:?", cell) for cell in cells):
            rows.append(cells)
        index += 1
    return rows, index


def add_markdown(doc: Document, markdown: str) -> None:
    lines = markdown.splitlines()
    index = 0
    while index < len(lines):
        line = lines[index].rstrip()
        if not line.strip():
            index += 1
            continue
        if line.startswith("|"):
            rows, index = parse_table(lines, index)
            if rows:
                table_obj = doc.add_table(rows=1, cols=len(rows[0]))
                table_obj.alignment = WD_TABLE_ALIGNMENT.CENTER
                table_obj.style = "Table Grid"
                for column, value in enumerate(rows[0]):
                    set_cell(table_obj.rows[0].cells[column], value, True, True)
                for row in rows[1:]:
                    cells = table_obj.add_row().cells
                    for column in range(len(rows[0])):
                        set_cell(cells[column], row[column] if column < len(row) else "")
                doc.add_paragraph()
            continue
        heading = re.match(r"^(#{1,4})\s+(.*)$", line)
        if heading:
            doc.add_heading(heading.group(2), level=len(heading.group(1)))
            index += 1
            continue
        if line.startswith("> "):
            doc.add_paragraph(line[2:], style="Intense Quote")
            index += 1
            continue
        if re.match(r"^\d+\.\s+", line):
            doc.add_paragraph(re.sub(r"^\d+\.\s+", "", line), style="List Number")
            index += 1
            continue
        if re.match(r"^[-*]\s+", line):
            doc.add_paragraph(re.sub(r"^[-*]\s+", "", line), style="List Bullet")
            index += 1
            continue
        text = re.sub(r"\*\*(.*?)\*\*", r"\1", line)
        text = re.sub(r"`(.*?)`", r"\1", text)
        doc.add_paragraph(text)
        index += 1


def write_docx(markdown_path: Path, docx_path: Path) -> None:
    document = Document()
    section = document.sections[0]
    section.top_margin = Inches(0.65)
    section.bottom_margin = Inches(0.65)
    section.left_margin = Inches(0.7)
    section.right_margin = Inches(0.7)
    document.styles["Normal"].font.name = "Microsoft YaHei"
    document.styles["Normal"]._element.rPr.rFonts.set(qn("w:eastAsia"), "Microsoft YaHei")
    document.styles["Normal"].font.size = Pt(10)
    for style_name in ("Heading 1", "Heading 2", "Heading 3", "Heading 4"):
        document.styles[style_name].font.name = "Microsoft YaHei"
        document.styles[style_name]._element.rPr.rFonts.set(qn("w:eastAsia"), "Microsoft YaHei")
    add_markdown(document, markdown_path.read_text(encoding="utf-8"))
    footer = section.footer.paragraphs[0]
    footer.alignment = WD_ALIGN_PARAGRAPH.CENTER
    footer.add_run(f"{VERSION} | {DATE}").font.size = Pt(8)
    document.save(docx_path)


def archive_old_files() -> None:
    archive = OUTPUT / "历史版本" / f"{VERSION}-生成前"
    archive.mkdir(parents=True, exist_ok=True)
    for path in OUTPUT.iterdir():
        if path.is_file() and path.suffix.lower() in {".md", ".docx", ".pdf", ".xlsx"}:
            shutil.move(str(path), str(archive / path.name))


def main() -> None:
    OUTPUT.mkdir(parents=True, exist_ok=True)
    archive_old_files()
    for base_name, builder in DOCUMENTS.items():
        markdown_path = OUTPUT / f"{base_name}.md"
        docx_path = OUTPUT / f"{base_name}.docx"
        markdown_path.write_text(builder(), encoding="utf-8", newline="\n")
        write_docx(markdown_path, docx_path)
    print(f"Generated {len(DOCUMENTS)} Markdown and {len(DOCUMENTS)} Word documents")


if __name__ == "__main__":
    main()
